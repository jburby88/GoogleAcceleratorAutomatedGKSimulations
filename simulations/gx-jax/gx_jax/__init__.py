# TPU and physics numerical defaults:
# 1. Enable float64 so static 1D geometry arrays, Laguerre Gauss-quadrature weights,
#    and quasineutrality/Ampere matrices are precomputed in IEEE FP64 before runtime cast.
if os.environ.get("JAX_ENABLE_X64") not in ("0", "false", "False"):
    jax.config.update("jax_enable_x64", True)
# 2. Prevent bfloat16 matmul truncation on TPU MXU (~3 decimal digits) during time-stepping.
jax.config.update("jax_default_matmul_precision", "highest")

