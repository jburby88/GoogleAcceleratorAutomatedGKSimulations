"""Enqueues high-uncertainty high-beta stellarator equilibria back into KR2 for GX/GENE validation.

Status (Phase 3 roadmap, ``docs/IMPLEMENTATION_PLAN.md``): only the hand-off of one validation run
into KR2's queue is implemented. The active-learning loop itself (acquisition function, batch
selection with diversity, budget enforcement) is deliberately not implemented: it needs the KR1
surrogates and a candidate design-space representation that do not exist yet (ML-02, deferred).

The generated GX/GENE input decks are templates pending physics sign-off: every value tagged
``TODO(david)`` is tracked in ``simulations/docs/OPEN_QUESTIONS.md`` (section 5).
They carry placeholder species profiles (GX ``[species]`` gradients, temperatures,
collisionality; GENE ``&species`` is still absent) that must come from the equilibrium/profile
data in Phase 3. Do not enqueue into a production queue before they are confirmed.

Queue safety (the KR2 cron driver polls ``queue/pending/`` and submits every folder it finds):

- A run id that already exists anywhere in the queue (``pending``, ``running``, ``completed``,
  ``needs_human``) is refused with :class:`RunAlreadyQueuedError`. Re-enqueueing a live run id
  would make the driver replace its running directory and submit it a second time.
- The run folder is written under a dot-prefixed staging directory (ignored by the driver),
  flushed to disk, then published with a single atomic ``os.rename``. The driver never sees a
  half-written folder (e.g. a ``gx.in`` without its ``[Geometry]`` section).
"""

from __future__ import annotations

import json
import math
import os
import re
import shutil
import uuid
from numbers import Real
from pathlib import Path

SAFE_ID_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")
QUEUE_STATE_DIRS = ("pending", "running", "completed", "needs_human")


class RunAlreadyQueuedError(FileExistsError):
    """The run id already exists in one of KR2's queue state directories."""


def _finite_real(value: object, label: str) -> float:
    if isinstance(value, bool) or not isinstance(value, Real) or not math.isfinite(value):
        raise ValueError(f"Invalid {label}: {value!r}")
    return float(value)


def _write_durable(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8") as handle:
        handle.write(text)
        handle.flush()
        os.fsync(handle.fileno())


def _fsync_dir(path: Path) -> None:
    fd = os.open(path, os.O_RDONLY)
    try:
        os.fsync(fd)
    finally:
        os.close(fd)


def _gx_species_tables(nspecies: int) -> str:
    # GXSRC-04b/c (docs/review/GXSRC.md; GX src/parameters.cu): without a [species] table GX
    # never fills its malloc'd species array, and add_Boltzmann_species defaults to false. GX
    # also forces beta = 0 when Boltzmann electrons are combined with beta > 0, so the
    # electromagnetic case must be fully kinetic.
    # TODO(david): confirm species gradients/collisionality (tprim=3.0, fprim=1.0, vnewk=0.01,
    # m_e/m_i=2.72e-4); placeholders until Phase-3 profile data exists (ZEN-05)
    if nspecies == 1:
        return (
            "[species]\n"
            "z = [1.0]\n"
            "mass = [1.0]\n"
            "dens = [1.0]\n"
            "temp = [1.0]\n"
            "tprim = [3.0]\n"
            "fprim = [1.0]\n"
            "vnewk = [0.01]\n"
            'type = ["ion"]\n\n'
            "[Boltzmann]\n"
            "add_Boltzmann_species = true\n"
            'Boltzmann_type = "electrons"\n'
            "tau_fac = 1.0\n\n"
        )
    return (
        "[species]\n"
        "z = [1.0, -1.0]\n"
        "mass = [1.0, 2.72e-4]\n"
        "dens = [1.0, 1.0]\n"
        "temp = [1.0, 1.0]\n"
        "tprim = [3.0, 3.0]\n"
        "fprim = [1.0, 1.0]\n"
        "vnewk = [0.01, 0.01]\n"
        'type = ["ion", "electron"]\n\n'
        "[Boltzmann]\n"
        "add_Boltzmann_species = false\n\n"
    )


def _gx_input(equilibrium_id: str, fidelity: str, beta_target: float) -> str:
    # DOM-05 (docs/review/DOMAIN.md): finite beta needs kinetic electrons (nspecies = 2), since
    # Boltzmann electrons carry no parallel current perturbation.
    nspecies = 2 if beta_target > 0.0 else 1
    # TODO(david): confirm resolution nx/ny/ntheta mappings for high/low fidelity
    return (
        f"# Generated by KR3 active-learning loop for {equilibrium_id}\n"
        "[Dimensions]\n"
        f"nx = {128 if fidelity == 'high' else 64}\n"
        f"ny = {64 if fidelity == 'high' else 32}\n"
        f"ntheta = {96 if fidelity == 'high' else 48}\n"
        "nhermite = 16\n"  # TODO(david): confirm nhermite=16, nlaguerre=8 (DOM-05)
        "nlaguerre = 8\n"
        f"nspecies = {nspecies}\n\n"
        "[Domain]\n"
        "y0 = 28.2\n"  # TODO(david): confirm stellarator [Domain] y0/x0/boundary (ZEN-02)
        'boundary = "linked"\n\n'
        "[Geometry]\n"
        # GXSRC-04a: GX reads geo_file (never geofilename); a NetCDF .eik.nc file needs
        # geo_option = "nc" ("eik" selects the ASCII eik.out reader).
        'geo_option = "nc"\n'
        f'geo_file = "{equilibrium_id}.eik.nc"\n\n'
        "[Time]\n"
        "t_max = 200.0\n"  # DOM-05; matches the diagnostics adapter's default sim_time_target
        "dt = 0.015\n"  # TODO(david): confirm dt=0.015 and cfl=0.75
        "cfl = 0.75\n\n"
        "[Dissipation]\n"
        "hyper = true\n"  # PHYS-04: GX's key is D_hyper (there is no `hyperviscosity`)
        "D_hyper = 0.05\n\n"  # TODO(david): confirm D_hyper=0.05 (was hyperviscosity=0.15)
        "[Restart]\n"
        "restart = false\n"
        "save_for_restart = true\n\n"
        "[Diagnostics]\n"  # DOM-05: fluxes/spectra the KR2 watchdog and gx-diagnose read
        "fluxes = true\n"
        "free_energy = true\n\n"
        f"{_gx_species_tables(nspecies)}"
        "[Physics]\n"
        f"beta = {beta_target}\n"
        # GX reads nonlinear_mode from [Physics] with no initialised default
        # (parameters.cu:L517), so it must be explicit for a nonlinear flux run.
        "nonlinear_mode = true\n"
    )


def _gene_parameters(equilibrium_id: str, fidelity: str, beta_target: float) -> str:
    # kymin is deliberately omitted: it is a per-equilibrium physics choice (DOM-05).
    return (
        f"&box\n  nx0 = {128 if fidelity == 'high' else 64}\n"
        f"  nky0 = {64 if fidelity == 'high' else 32}\n"
        f"  nz0 = {96 if fidelity == 'high' else 48}\n"
        "  nv0 = 16\n  nw0 = 8\n/\n"  # TODO(david): confirm nv0=16, nw0=8 (DOM-05)
        f"&geometry\n  magn_geometry = 'gist'\n  geomfile = '{equilibrium_id}'\n/\n"
        f"&general\n  calc_dt = .true.\n  simtimelim = 200.0\n  dt_max = 0.015\n  courant = 0.75\n  hyp_z = 0.2\n  beta = {beta_target}\n/\n"  # TODO(david): confirm general gene parameters
        "&in_out\n  read_checkpoint = .false.\n/\n"
    )


def _slurm_script(run_id: str, solver: str, slurm_account: str) -> str:
    partition = "gh" if solver == "GX" else "normal"  # TODO(david): confirm partitions
    exec_cmd = "ibrun gx gx.in" if solver == "GX" else 'ibrun "${GENE_BIN:-gene}"'
    return (
        "#!/bin/bash\n"
        "# TACC Vista (gh) / Frontera batch script\n"
        f"#SBATCH -J {run_id}\n"
        f"#SBATCH -A {slurm_account}\n"
        "#SBATCH -o slurm.out\n"
        "#SBATCH -e slurm.err\n"
        f"#SBATCH -p {partition}\n"
        "#SBATCH -N 1\n"
        "#SBATCH -n 1\n"
        "#SBATCH -t 02:00:00\n\n"  # TODO(david): confirm walltime 02:00:00
        "set -euo pipefail\n"
        f"{exec_cmd}\n"
    )


def enqueue_validation_run(
    *,
    kr2_pending_dir: Path,
    run_id: str,
    equilibrium_id: str,
    campaign_id: str = "kr3_active_learning",
    solver: str = "GX",
    fidelity: str = "high",
    surrogate_epistemic_std: float = 0.0,
    beta_target: float = 0.035,
    slurm_account: str = "TG-PHY240001",
) -> Path:
    """Atomically create a ready-to-babysit GX or GENE run folder in KR2's ``queue/pending/``.

    ``kr2_pending_dir`` must be the ``pending`` directory of a KR2 queue (``<queue_dir>/pending``)
    so that duplicates can be checked against its sibling state directories. Raises
    :class:`ValueError` on invalid input and :class:`RunAlreadyQueuedError` if ``run_id`` is
    already queued, running, completed or escalated. Callers wanting one validation per design
    point should derive ``run_id`` deterministically from it. Returns the published folder.
    """
    for label, value in (
        ("run_id", run_id),
        ("equilibrium_id", equilibrium_id),
        ("campaign_id", campaign_id),
        ("slurm_account", slurm_account),
    ):
        if not isinstance(value, str) or not SAFE_ID_RE.match(value):
            raise ValueError(f"Unsafe or invalid {label}: {value!r}")
    if not isinstance(solver, str) or solver.upper() not in {"GX", "GENE"}:
        raise ValueError(f"Invalid solver: {solver!r}")
    solver_upper = solver.upper()
    if not isinstance(fidelity, str) or fidelity not in {"low", "high"}:
        raise ValueError(f"Invalid fidelity: {fidelity!r}")
    epistemic_std = _finite_real(surrogate_epistemic_std, "surrogate_epistemic_std")
    if epistemic_std < 0.0:
        raise ValueError(f"Invalid surrogate_epistemic_std (must be >= 0): {epistemic_std!r}")
    beta = _finite_real(beta_target, "beta_target")
    if not 0.0 <= beta < 1.0:
        raise ValueError(f"Invalid beta_target (must lie in [0, 1)): {beta!r}")

    pending_dir = Path(kr2_pending_dir).resolve()
    if pending_dir.name != "pending":
        raise ValueError(
            f"kr2_pending_dir must be a KR2 queue's 'pending' directory: {pending_dir}"
        )
    queue_root = pending_dir.parent
    for state in QUEUE_STATE_DIRS:
        existing = queue_root / state / run_id
        if existing.exists() or existing.is_symlink():
            raise RunAlreadyQueuedError(f"run_id {run_id!r} already exists in queue/{state}/")

    meta = {
        "schema_version": "1.0",
        "origin_workstream": "kr3-transport-consistent-design",
        "campaign_id": campaign_id,
        "equilibrium_id": equilibrium_id,
        "geometry_id": equilibrium_id,
        "fidelity": fidelity,
        "surrogate_epistemic_std": round(epistemic_std, 5),
        "beta_target": round(beta, 5),
    }
    files = {"run_meta.json": json.dumps(meta, indent=2, allow_nan=False) + "\n"}
    if solver_upper == "GX":
        files["gx.in"] = _gx_input(equilibrium_id, fidelity, beta)
    else:
        files["parameters"] = _gene_parameters(equilibrium_id, fidelity, beta)
    files["submit.slurm"] = _slurm_script(run_id, solver_upper, slurm_account)

    pending_dir.mkdir(parents=True, exist_ok=True)
    staging = pending_dir / f".kr3-staging-{run_id}-{uuid.uuid4().hex[:12]}"
    staging.mkdir()
    try:
        for name, text in files.items():
            _write_durable(staging / name, text)
        (staging / "submit.slurm").chmod(0o755)
        _fsync_dir(staging)
        run_folder = pending_dir / run_id
        if run_folder.exists() or run_folder.is_symlink():  # lost a race since the check above
            raise RunAlreadyQueuedError(f"run_id {run_id!r} already exists in queue/pending/")
        os.rename(staging, run_folder)
    except BaseException:
        shutil.rmtree(staging, ignore_errors=True)
        raise
    _fsync_dir(pending_dir)
    return run_folder
